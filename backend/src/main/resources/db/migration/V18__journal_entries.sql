-- V18: journal entries — free-text daily diary notes, one per user per date.
-- Postgres/prod only (H2 dev builds its schema from JPA entities). Online-only resource
-- (not part of delta-sync); both clients read/write it directly over REST.
CREATE TABLE journal_entries (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firebase_uid character varying(255)   NOT NULL,
    date         date                     NOT NULL,
    note         text                     NOT NULL,
    updated_at   timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT uq_journal_uid_date UNIQUE (firebase_uid, date)
);
CREATE INDEX idx_journal_uid_date ON journal_entries (firebase_uid, date);
